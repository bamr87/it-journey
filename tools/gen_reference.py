#!/usr/bin/env python3
"""gen_reference.py — generate docs/reference/ from the files that define it.

Hand-copied inventories drift: the old docs/workflows/GITHUB_ACTIONS.md listed
workflows that no longer existed and missed most of the ones that did. This
script derives the reference from source instead (fleet docs framework,
UPS-DOC-05):

  docs/reference/workflows.md     from .github/workflows/*.yml (name, triggers,
                                  cron schedules, kill-switch variables, how
                                  the steps call a model, the banner line)
  docs/reference/make-targets.md  from the Makefile (`make help` text, then
                                  every other rule with its comment or echo)

Usage:
  python3 tools/gen_reference.py           rewrite the generated files
  python3 tools/gen_reference.py --check   exit 1 when a generated file is stale

`make docs` and `make docs-check` wrap it (with tools/docs_index.py). Needs
Python 3.8+ and PyYAML, like the rest of the repo's tooling.
"""
import argparse
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - environment guard
    print("pyyaml required: pip install pyyaml", file=sys.stderr)
    sys.exit(2)

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "docs" / "reference"
COMMAND = "python3 tools/gen_reference.py"

# A switch is any `vars.*_ENABLED`, or any repo variable compared to 'true'/'false'.
SWITCH_RE = re.compile(r"vars\.([A-Z0-9_]+_ENABLED)\b|vars\.([A-Z0-9_]+)\s*[!=]=\s*'(?:true|false)'")
CLAUDE_CLI_RE = re.compile(r"(^|[\s;&|(])claude\s+-p\b", re.M)


def header(source):
    return "<!-- GENERATED by `%s` from %s — do not edit by hand -->" % (COMMAND, source)


def cell(text):
    """One Markdown table cell: single line, escaped pipes, an em dash when empty."""
    text = " ".join(str(text or "").split())
    return text.replace("|", "\\|") if text else "—"


# --- workflows ----------------------------------------------------------------

def banner(path, text):
    """The `# <file> — <purpose>` line many workflow headers open with, if any."""
    pattern = re.compile(r"^#\s*%s\s+[—-]+\s+(.+?)\s*$" % re.escape(path.name))
    for line in text.splitlines()[:12]:
        m = pattern.match(line)
        if m:
            return m.group(1).rstrip(".")
    return ""


def switches(text):
    found = set()
    for enabled, compared in SWITCH_RE.findall(text):
        found.add(enabled or compared)
    return sorted(found)


def model_calls(data):
    """How the workflow's own steps reach a model (reusable callees are not followed)."""
    kinds = set()
    for job in (data.get("jobs") or {}).values():
        steps = job.get("steps") if isinstance(job, dict) else None
        for step in steps or []:
            if not isinstance(step, dict):
                continue
            uses, run = str(step.get("uses") or ""), str(step.get("run") or "")
            if "actions/claude-run@" in uses:
                kinds.add("`claude-run`")
            if "anthropics/claude-code-action@" in uses:
                kinds.add("`claude-code-action`")
            if CLAUDE_CLI_RE.search(run):
                kinds.add("`claude -p`")
            if "agentic_validate.py" in run:
                kinds.add("quest engine")
    return ", ".join(sorted(kinds))


def triggers(on):
    if isinstance(on, str):
        return "`%s`" % on
    if isinstance(on, list):
        return " · ".join("`%s`" % e for e in on)
    parts = []
    for event, spec in (on or {}).items():
        detail = []
        if event == "schedule" and isinstance(spec, list):
            detail.append(", ".join("cron `%s`" % entry.get("cron", "?") for entry in spec))
        elif isinstance(spec, dict):
            if spec.get("types"):
                detail.append(", ".join(spec["types"]))
            if spec.get("workflows"):
                detail.append("after " + ", ".join("`%s`" % w for w in spec["workflows"]))
        parts.append("`%s`" % event + (" (%s)" % "; ".join(detail) if detail else ""))
    return " · ".join(parts)


def workflows_reference():
    rows = []
    for path in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        text = path.read_text(encoding="utf-8")
        data = yaml.safe_load(text) or {}
        # YAML 1.1 reads a bare `on:` key as the boolean True.
        on = data.get("on", data.get(True))
        rows.append("| [`%s`](../../.github/workflows/%s) | %s | %s | %s | %s | %s |" % (
            path.name, path.name, cell(data.get("name")), cell(triggers(on)),
            cell(", ".join("`%s`" % s for s in switches(text))),
            cell(model_calls(data)), cell(banner(path, text))))
    lines = [
        header("`.github/workflows/*.yml`"),
        "# Workflow reference",
        "",
        "> Every GitHub Actions workflow in this repository — its triggers, cron schedules, kill-switch variables and how it calls a model — generated from the workflow files.",
        "",
        "What each lane does and how the lanes fit together is explained in [`.github/workflows/README.md`](../../.github/workflows/README.md) and [`scripts/ai/README.md`](../../scripts/ai/README.md). **Switches** lists every `vars.*_ENABLED` variable the file reads, and any other repo variable it compares to `'true'`/`'false'`; an AI lane stays off until its switch and the Claude auth secret are set. **Model** names how the file's own steps reach a model: the fleet's `claude-run` action, `claude-code-action`, the `claude -p` CLI, or the agentic quest engine (`agentic_validate.py`); a reusable workflow it calls is listed on its own row. **Purpose** is the file's own `# <file> — <purpose>` banner line, when it has one. Run `make docs` after adding, removing or retriggering a workflow.",
        "",
        "| Workflow | Name | Triggers | Switches | Model | Purpose |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    return "\n".join(lines + rows) + "\n"


# --- make targets -------------------------------------------------------------

RULE_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9_.-]*)\s*:(?!=)(.*)$")
ECHO_RE = re.compile(r'^\t@echo\s+"(.*)"\s*$')
HELP_ROW_RE = re.compile(r"^\s*make\s+(\S+)(.*?)\s+-\s+(.+)$")


def parse_rules(lines):
    """{target: (prerequisites, comment, first echo)} for every rule, in file order."""
    rules = {}
    for i, line in enumerate(lines):
        m = RULE_RE.match(line)
        if not m or m.group(1).startswith("."):
            continue
        target, prereqs = m.group(1), m.group(2).split("#", 1)[0].split()
        comment = []
        j = i - 1
        while j >= 0 and lines[j].startswith("#"):
            comment.insert(0, lines[j].lstrip("#").strip())
            j -= 1
        echo = ""
        for body in lines[i + 1:]:
            if not body.startswith("\t"):
                break
            e = ECHO_RE.match(body)
            if e:
                echo = e.group(1)
                break
        rules.setdefault(target, (prereqs, " ".join(c for c in comment if c), echo))
    return rules


def parse_help(lines, rules):
    """[(section, [(command, description)])] from the `help` rule's echo lines."""
    if "help" not in rules:
        return []
    start = next(i for i, line in enumerate(lines) if line.startswith("help:"))
    sections, current = [], None
    for body in lines[start + 1:]:
        if not body.startswith("\t"):
            break
        e = ECHO_RE.match(body)
        if not e:
            continue
        text = e.group(1).strip()
        if not text or set(text) <= {"=", "-"} or text.endswith("commands:"):
            continue
        row = HELP_ROW_RE.match(e.group(1))
        if row:
            command = ("make %s %s" % (row.group(1), row.group(2).strip())).strip()
            if current is None:
                current = ("Commands", [])
                sections.append(current)
            current[1].append((row.group(1), command, row.group(3).strip()))
        else:
            current = (" ".join(text.split()), [])
            sections.append(current)
    return [s for s in sections if s[1]]


GROUP_COMMENT_RE = re.compile(r"\btargets?$", re.I)


def tidy(text):
    """A rule's comment or echo as a description: first sentence, no emoji or ellipsis."""
    text = text.replace("\\$", "$").replace("$$", "$")
    text = re.sub(r"^[^\w(`'\"]+", "", text).rstrip(". ").rstrip("…")
    return re.split(r"(?<=[.!?])\s+(?=[A-Z])", text, maxsplit=1)[0].rstrip(".")


def describe_rule(comment, echo):
    if comment and not GROUP_COMMENT_RE.search(comment):
        return tidy(comment)
    return tidy(echo) if echo else ""


def with_prereqs(description, prereqs):
    if prereqs:
        description = (description + " " if description else "") + "(runs %s)" % ", ".join("`%s`" % p for p in prereqs)
    return description


def make_targets_reference():
    lines = (ROOT / "Makefile").read_text(encoding="utf-8").splitlines()
    rules = parse_rules(lines)
    help_sections = parse_help(lines, rules)
    out = [
        header("the `Makefile`"),
        "# Make targets",
        "",
        "> Every `make` target in the Makefile — the ones `make help` lists, in its groups, then the rest — generated from the Makefile itself.",
        "",
        "Descriptions come from the `help` rule's text. A target `make help` does not list falls back to the first sentence of the comment above its rule, else the first message it echoes. To document a target, add it to `make help`, then run `make docs`.",
        "",
    ]
    listed = set()
    for section, rows in help_sections:
        out += ["## %s" % section, "", "| Command | Description |", "| --- | --- |"]
        for target, command, description in rows:
            listed.add(target)
            prereqs = rules.get(target, ([], "", ""))[0]
            out.append("| `%s` | %s |" % (command, cell(with_prereqs(description, prereqs))))
        out.append("")
    rest = [(t, r) for t, r in rules.items() if t not in listed and t != "help"]
    if rest:
        out += ["## Not in `make help`", "", "| Command | Description |", "| --- | --- |"]
        for target, (prereqs, comment, echo) in rest:
            out.append("| `make %s` | %s |" % (target, cell(with_prereqs(describe_rule(comment, echo), prereqs))))
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


# --- main ---------------------------------------------------------------------

OUTPUTS = {
    "workflows.md": workflows_reference,
    "make-targets.md": make_targets_reference,
}


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate docs/reference/ from source.")
    ap.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    args = ap.parse_args(argv)
    stale = []
    for name, build in OUTPUTS.items():
        path = OUT_DIR / name
        fresh = build()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == fresh:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(fresh, encoding="utf-8")
            print("wrote %s" % path.relative_to(ROOT).as_posix())
    if stale:
        print("stale: %s — run `make docs`" % ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
